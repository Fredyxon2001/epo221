const assert = require('node:assert/strict');
const { load } = require('./security-loader.cjs');
const { reviewState, safeReferenceUrl, validReviewDates, OPERATION_TOPICS } = load('src/lib/operation-governance.ts');
const hash = 'a'.repeat(64), today = '2026-10-07';
const valid = { estado: 'aprobado', huella_aprobada: hash, fecha_revision: '2026-10-01', proxima_revision: today };
assert.equal(reviewState(valid, hash, today).state, 'vigente', 'The final review day remains valid in school local time');
assert.equal(reviewState({ ...valid, fuentes_aprobadas: hash }, hash, today, hash).state, 'vigente');
assert.equal(reviewState({ ...valid, fuentes_aprobadas: hash }, hash, today, 'b'.repeat(64)).state, 'pendiente', 'Static policy changes invalidate approval');
assert.equal(reviewState({ ...valid, estado: 'borrador' }, hash, today).state, 'pendiente');
assert.equal(reviewState(valid, 'b'.repeat(64), today).state, 'pendiente', 'Changed public content invalidates approval');
assert.equal(reviewState(valid, null, today).state, 'pendiente', 'Unavailable fingerprint fails closed');
assert.equal(reviewState({ ...valid, proxima_revision: '2026-10-06' }, hash, today).state, 'vencido');
assert.equal(reviewState({ ...valid, fecha_revision: '2026-10-08' }, hash, today).state, 'pendiente');
assert.equal(reviewState({ ...valid, fecha_revision: null }, hash, today).state, 'pendiente');
assert.equal(reviewState({ ...valid, proxima_revision: '2026-02-30' }, hash, today).state, 'pendiente');
assert.equal(validReviewDates(null, null), true, 'Drafts can have no dates');
assert.equal(validReviewDates('2028-02-29', '2028-03-01'), true);
assert.equal(validReviewDates('2026-02-29', null), false);
assert.equal(validReviewDates('2026-10-07', '2026-10-06'), false);
assert.equal(safeReferenceUrl(''), true);
assert.equal(safeReferenceUrl('https://escuela.example/acta#folio'), true);
for (const url of ['javascript:alert(1)', 'http://escuela.example', 'https://admin:clave@escuela.example', 'https://escuela.example/acta\n']) assert.equal(safeReferenceUrl(url), false);
assert.equal(Object.keys(OPERATION_TOPICS).length, 8);
const sourcesA = load('src/lib/operation-public-sources.ts', {}, { EPO_NOTICE_DIGEST: hash, PRIVACY_NOTICE_URL: 'https://escuela.example/aviso' });
const sourcesB = load('src/lib/operation-public-sources.ts', {}, { EPO_NOTICE_DIGEST: hash, PRIVACY_NOTICE_URL: 'https://escuela.example/aviso-nuevo' });
assert.notEqual(sourcesA.publicPolicyFingerprint(), sourcesB.publicPolicyFingerprint(), 'Official notice URL changes require review');
assert.equal(sourcesA.policySourcesFor('privacidad', hash), hash);
assert.equal(sourcesA.policySourcesFor('retenciones', hash), null);
assert.throws(() => load('src/lib/operation-public-sources.ts').publicPolicyFingerprint(), /huella/);
console.log('PASS governance: changed/expired approval, school date limits, empty drafts and safe references.');
